#!/usr/bin/env python3
"""Turns packages/protocol/vectors/v1.json into C++ checks for the firmware.

Run by the Makefile before every host test build, so the firmware structs and
command parser are always checked against the same bytes as the TypeScript
codec. Usage: gen_vectors.py <vectors.json> <output.h>
"""
import json
import sys

STRUCTS = {
    "record": "RecordMessage",
    "syncDone": "SyncDoneMessage",
    "scoreEvent": "ScoreEventMessage",
    "approval": "ApprovalMessage",
    "error": "ErrorMessage",
}


def const_name(namespace, name):
    return f"{namespace}::k{name[0].upper()}{name[1:]}"


def byte_array(hex_string):
    return ", ".join(f"0x{b}" for b in hex_string.split())


def struct_check(struct, label, hex_string, fields, type_namespace=None):
    lines = [f"  {{  // {label}", f"    const uint8_t bytes[] = {{{byte_array(hex_string)}}};", f"    {struct} v = {{}};"]
    for name, value in fields.items():
        if name == "type":
            lines.append(f"    v.type = {const_name(type_namespace, value)};")
        else:
            lines.append(f"    v.{name} = {value}u;" if value >= 0 else f"    v.{name} = {value};")
    lines.append(f'    CHECK_MSG(sizeof(v) == sizeof(bytes), "{label}: size");')
    lines.append(f'    CHECK_MSG(memcmp(&v, bytes, sizeof(v)) == 0, "{label}: bytes");')
    lines.append("  }")
    return lines


def command_check(label, hex_string, fields):
    lines = [
        f"  {{  // {label}",
        f"    const uint8_t bytes[] = {{{byte_array(hex_string)}}};",
        "    ParsedCommand c;",
        f'    CHECK_MSG(parseCommand(bytes, sizeof(bytes), c) == ErrorCode::kNone, "{label}: parses");',
        f'    CHECK_MSG(c.opcode == {const_name("CommandOpcode", fields["type"])}, "{label}: opcode");',
    ]
    for name, value in fields.items():
        if name == "type":
            continue
        if name == "effects":
            lines.append(f'    CHECK_MSG(c.effectCount == {len(value)}, "{label}: effectCount");')
            for i, effect in enumerate(value):
                lines.append(f'    CHECK_MSG(c.effects[{i}] == {effect}, "{label}: effects[{i}]");')
        elif isinstance(value, str):
            lines.append(f'    CHECK_MSG(strcmp(c.{name}, {json.dumps(value)}) == 0, "{label}: {name}");')
        else:
            lines.append(f'    CHECK_MSG(c.{name} == {value}u, "{label}: {name}");')
    lines.append("  }")
    return lines


def main(source, target):
    with open(source) as f:
        vectors = json.load(f)
    out = [
        "// GENERATED by firmware/test/gen_vectors.py from packages/protocol/vectors/v1.json.",
        "// Do not edit; edit the vectors and PROTOCOL.md instead.",
        "#pragma once",
        "#include <string.h>",
        '#include "fidget_protocol.h"',
        "",
        f"static_assert(jimmyit::kProtocolVersion == {vectors['protocolVersion']}, \"vectors are for another protocol version\");",
        "",
        "inline void runVectorTests() {",
        "  using namespace jimmyit;",
    ]
    for v in vectors["input"]:
        out += struct_check("InputPacket", f"input: {v['name']}", v["hex"], v["fields"])
    for v in vectors["info"]:
        out += struct_check("DeviceInfo", f"info: {v['name']}", v["hex"], v["fields"])
    for v in vectors["message"]:
        out += struct_check(STRUCTS[v["fields"]["type"]], f"message: {v['name']}", v["hex"], v["fields"], "MessageType")
    for v in vectors["command"]:
        out += command_check(f"command: {v['name']}", v["hex"], v["fields"])
    out.append("}")
    with open(target, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
